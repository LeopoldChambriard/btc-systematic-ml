"""Paste the backtest tables of a run summary into README.md between result markers.

    python scripts/update_readme_results.py results/default/summary.md README.md
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def extract_backtest_block(summary: str) -> str:
    """From the '## Backtest' heading up to (excluding) '## Notes', headings demoted one level."""
    match = re.search(r"^## Backtest.*?(?=^## Notes|\Z)", summary, flags=re.S | re.M)
    if not match:
        raise SystemExit("No '## Backtest' section found in the summary")
    return re.sub(r"^(#{2,})", r"#\1", match.group(0).strip(), flags=re.M)


def main(summary_path: str, readme_path: str) -> None:
    summary = Path(summary_path).read_text()
    run = re.search(r"^# Run summary: `(.+?)`", summary, flags=re.M)
    readme = Path(readme_path).read_text()
    if START not in readme or END not in readme:
        raise SystemExit(f"Markers {START} / {END} not found in {readme_path}")

    block = (
        f"_Generated by `make readme` from `results/{run.group(1) if run else '?'}/summary.md`. "
        "Re-run to refresh._\n\n" + extract_backtest_block(summary)
    )
    head, rest = readme.split(START, 1)
    _, tail = rest.split(END, 1)
    Path(readme_path).write_text(f"{head}{START}\n{block}\n{END}{tail}")
    print(f"Updated {readme_path}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    main(sys.argv[1], sys.argv[2])
